#!/usr/bin/env node
// Build the local dev schema from a READ-ONLY export of prod's live definitions.
//
//   node dev/gen-schema.mjs <prod_ddl.json> > dev/supabase/migrations/00000000000001_prod_subset.sql
//
// prod_ddl.json comes from the catalog query in README.md (Dev copy) (columns, constraints, indexes,
// triggers, functions, policies of the COC tables). Only the tables the MCP server touches are
// built. Anything that refers to objects outside this subset (FKs to auth.users, policies calling
// functions we do not copy) is skipped and listed on stderr, so the dev copy never silently differs.
import { readFileSync } from "node:fs";

const ddl = JSON.parse(readFileSync(process.argv[2], "utf8"));
const TABLES = ["clients", "sites", "subsections", "subsection_documents", "coc_import_batches", "coc_db_schedule", "coc_certificates"];
const COC = new Set(["coc_import_batches", "coc_db_schedule", "coc_certificates"]);
const KNOWN_TYPES = /^(uuid|text|integer|bigint|smallint|boolean|numeric(\(.*\))?|date|jsonb|json|real|double precision|timestamp with time zone|timestamp without time zone|character varying(\(\d+\))?|text\[\]|uuid\[\]|integer\[\]|jsonb\[\]|app_role)$/;
const SAFE_DEFAULT = /^(gen_random_uuid\(\)|now\(\)|true|false|-?\d+(\.\d+)?|'[^']*'(::[a-z_ ]+(\[\])?)?|ARRAY\[\]::[a-z_ ]+\[\])$/;
const skipped = [];
const out = [];

out.push(`-- Local dev copy of prod's COC schema subset. GENERATED by dev/gen-schema.mjs from a read-only
-- catalog export (${new Date().toISOString().slice(0, 10)}). Do not edit by hand; never apply to prod.
create extension if not exists pgcrypto;
do $$ begin create type public.app_role as enum (${ddl.enums.find(e => e.t === "app_role").v.map(v => `'${v}'`).join(", ")});
exception when duplicate_object then null; end $$;
create table if not exists public.user_roles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null,
  role public.app_role not null,
  created_at timestamptz not null default now()
);
`);

for (const t of TABLES) {
  const cols = ddl.columns.filter(c => c.t === t);
  const lines = cols.map(c => {
    let type = c.type;
    if (!KNOWN_TYPES.test(type)) { skipped.push(`${t}.${c.c}: type ${type} -> text`); type = "text"; }
    let def = "";
    if (c.def != null) {
      if (SAFE_DEFAULT.test(c.def.trim())) def = ` default ${c.def}`;
      else skipped.push(`${t}.${c.c}: default ${c.def} dropped`);
    }
    return `  ${JSON.stringify(c.c)} ${type}${c.null === "NO" ? " not null" : ""}${def}`;
  });
  const hasPk = ddl.constraints.some(k => k.t === `${t}` && k.def.startsWith("PRIMARY KEY"));
  if (!COC.has(t) || !hasPk) lines.push(`  primary key ("id")`);
  out.push(`create table public.${t} (\n${lines.join(",\n")}\n);`);
}

for (const k of ddl.constraints) {
  const t = k.t.replace(/^public\./, "");
  if (k.def.startsWith("FOREIGN KEY")) {
    const ref = k.def.match(/REFERENCES ([a-z_.]+)\(/)?.[1]?.replace(/^public\./, "");
    if (!TABLES.includes(ref)) { skipped.push(`constraint ${k.n}: FK to ${ref}`); continue; }
  }
  out.push(`alter table public.${t} add constraint ${k.n} ${k.def};`);
}

for (const ix of ddl.indexes) {
  if (/_pkey ON /.test(ix)) continue;
  out.push(`${ix.replace(/^CREATE (UNIQUE )?INDEX /, "CREATE $1INDEX IF NOT EXISTS ")};`);
}

for (const f of ddl.functions) out.push(`${f.def.trim()};`);
for (const tr of ddl.triggers) out.push(`${tr.def};`);

for (const t of TABLES) out.push(`alter table public.${t} enable row level security;`);
const copiedFns = new Set(ddl.functions.map(f => f.n));
for (const p of ddl.policies) {
  const expr = `${p.qual ?? ""} ${p.check ?? ""}`;
  const calls = [...expr.matchAll(/([a-z_]+)\(/g)].map(m => m[1]).filter(n => !["auth", "uid", "coalesce", "upper", "lower"].includes(n));
  const missing = calls.filter(n => !copiedFns.has(n) && !["has_role"].includes(n));
  if (missing.length) { skipped.push(`policy "${p.n}" on ${p.t}: calls ${missing.join(", ")}`); continue; }
  const roles = p.roles.replace(/[{}]/g, "");
  const using = p.qual ? ` using (${p.qual})` : "";
  const check = p.check ? ` with check (${p.check})` : "";
  out.push(`create policy ${JSON.stringify(p.n)} on public.${p.t} for ${p.cmd.toLowerCase()} to ${roles}${using}${check};`);
}
// Non-COC tables: prod has richer per-role rules; the dev copy only needs staff read access.
for (const t of TABLES.filter(t => !COC.has(t))) {
  out.push(`create policy "dev staff read ${t}" on public.${t} for select to authenticated using (not public.has_role(auth.uid(), 'Client'));`);
}
out.push(`create policy "dev read own roles" on public.user_roles for select to authenticated using (user_id = auth.uid());`);
out.push(`alter table public.user_roles enable row level security;`);

process.stdout.write(out.join("\n\n") + "\n");
if (skipped.length) process.stderr.write(`skipped/adjusted (${skipped.length}):\n  ${skipped.join("\n  ")}\n`);
